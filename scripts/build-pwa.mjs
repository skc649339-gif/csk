/** Run AFTER next build. Reproducible, content-addressed shell; no runtime CDN. */
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateLicenseNotices } from './license-notices.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

async function walk(directory, prefix = '') {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (entry.isDirectory()) result.push(...await walk(path.join(directory, entry.name), name + '/'));
    else result.push(name);
  }
  return result;
}

export function normalizeBasePath(value = '') {
  if (value && !/^\/[A-Za-z0-9._~-]+(?:\/[A-Za-z0-9._~-]+)*$/.test(value)) throw new Error('Invalid NEXT_PUBLIC_BASE_PATH: use /repo without a trailing slash.');
  return value;
}

export async function createPrecache(directory, basePath = '') {
  basePath = normalizeBasePath(basePath);
  const files = await walk(directory);
  // All generated JS/CSS/font chunks are needed for code-split engine, form,
  // local interpretation and React navigation. Only the two core HTML shells
  // are preloaded; successfully visited reference pages are cached at runtime.
  const selected = files.filter(file =>
    file.startsWith('_next/static/') || file.startsWith('icons/') || /^(?:chart\/)?__next\..*\.txt$/.test(file) ||
    ['index.html', 'chart/index.html', 'index.txt', 'chart/index.txt', 'manifest.webmanifest'].includes(file)
  ).filter(file => !file.endsWith('.map'));
  for (const required of ['index.html', 'chart/index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png']) {
    if (!selected.includes(required)) throw new Error(`PWA core resource missing: ${required}`);
  }
  const entries = await Promise.all(selected.sort().map(async file => {
    const bytes = await readFile(path.join(directory, file));
    const url = file === 'index.html' ? '/' : file === 'chart/index.html' ? '/chart/' : '/' + file;
    return { url: basePath + url, sha256: hash(bytes), bytes: bytes.length };
  }));
  return { version: hash(JSON.stringify(entries)).slice(0, 20), basePath, entries };
}

export function createWorkerSource(manifest) {
  return `/* Generated by scripts/build-pwa.mjs. Do not edit. */
'use strict';
const VERSION = ${JSON.stringify(manifest.version)};
const BASE = ${JSON.stringify(manifest.basePath || '')};
const CORE = ${JSON.stringify(manifest.entries.map(({ url, sha256 }) => ({ url, sha256 })))};
const PREFIX = 'ziwei-pwa-' + (BASE ? encodeURIComponent(BASE) : 'root') + '-';
const PRECACHE = PREFIX + 'precache-' + VERSION;
const RUNTIME = PREFIX + 'runtime-' + VERSION;
const READY = BASE + '/__ziwei_cache_ready__';
const CORE_PAGES = new Set([BASE + '/', BASE + '/chart/']);
const MAX_RUNTIME = 80;
const hex = bytes => Array.from(new Uint8Array(bytes), n => n.toString(16).padStart(2, '0')).join('');

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(PRECACHE);
    try {
      // Bound parallel requests to avoid memory pressure on iPhone.
      let cursor = 0;
      await Promise.all(Array.from({ length: Math.min(6, CORE.length) }, async () => {
        while (cursor < CORE.length) {
          const entry = CORE[cursor++];
          const response = await fetch(new Request(entry.url, { cache: 'reload', credentials: 'same-origin' }));
          if (!response.ok || response.type === 'opaque') throw new Error('PWA resource unavailable: ' + entry.url);
          const digest = hex(await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer()));
          if (digest !== entry.sha256) throw new Error('PWA resource integrity mismatch: ' + entry.url);
          await cache.put(entry.url, response);
        }
      }));
      await cache.put(READY, new Response(VERSION));
    } catch (error) {
      await caches.delete(PRECACHE);
      throw error;
    }
    // No skipWaiting: an update must never refresh an unfinished birth form.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(PREFIX) && name !== PRECACHE && name !== RUNTIME).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type !== 'CACHE_STATUS' || !event.ports?.[0]) return;
  event.waitUntil((async () => {
    const cache = await caches.open(PRECACHE);
    const complete = !!(await cache.match(READY)) && (await Promise.all(CORE.map(entry => cache.match(entry.url)))).every(Boolean);
    event.ports[0].postMessage({ type: 'CACHE_STATUS', ready: complete, version: VERSION, resources: CORE.length });
  })());
});

async function remember(request, response) {
  if (!response.ok || response.type === 'opaque' || response.headers.get('cache-control')?.includes('no-store')) return;
  const cache = await caches.open(RUNTIME);
  await cache.put(request, response.clone());
  const keys = await cache.keys();
  await Promise.all(keys.slice(0, Math.max(0, keys.length - MAX_RUNTIME)).map(key => cache.delete(key)));
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  // No cross-origin, API or mutation interception. Birth data is never sent.
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE + '/') || url.pathname.startsWith(BASE + '/api/') || url.pathname === BASE + '/sw.js') return;
  event.respondWith((async () => {
    const core = await caches.open(PRECACHE);
    const corePage = request.mode === 'navigate' && CORE_PAGES.has(url.pathname);
    // A shell and its hashed chunks form one version. Keep these together.
    // Next static export uses .txt for RSC and appends a router cache-bust token.
    // That token does not change the exported bytes. Never strip real queries.
    const rscArtifact = url.pathname.endsWith('.txt') && url.searchParams.has('_rsc') && [...url.searchParams.keys()].every(key => key === '_rsc');
    const preloaded = await core.match(corePage ? url.pathname : rscArtifact ? url.origin + url.pathname : request);
    if (preloaded) return preloaded;
    try {
      const response = await fetch(request);
      event.waitUntil(remember(request, response).catch(() => {}));
      return response;
    } catch (error) {
      const runtime = await caches.open(RUNTIME);
      // Preserve the query and Vary headers; never return HTML for an RSC fetch.
      const visited = await runtime.match(request);
      if (visited) return visited;
      if (request.mode === 'navigate') return new Response('<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>暂未缓存</title><body style="font-family:system-ui;padding:32px"><h1>此页面尚未缓存</h1><p>请联网访问一次后再离线打开。</p><a href="' + BASE + '/">返回紫微斗数</a></body></html>', { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
      throw error;
    }
  })());
});
`;
}

export async function buildPwa(directory = path.join(root, 'out'), basePath = process.env.NEXT_PUBLIC_BASE_PATH || '', options = {}) {
  basePath = normalizeBasePath(basePath);
  const appManifest = JSON.parse(await readFile(path.join(root, 'public/manifest.webmanifest'), 'utf8'));
  for (const field of ['id', 'start_url', 'scope']) appManifest[field] = basePath + '/';
  for (const icon of appManifest.icons) icon.src = basePath + icon.src;
  await writeFile(path.join(directory, 'manifest.webmanifest'), JSON.stringify(appManifest, null, 2) + '\n');
  const manifest = await createPrecache(directory, basePath);
  const worker = createWorkerSource(manifest);
  await writeFile(path.join(directory, 'sw.js'), worker);
  await writeFile(path.join(directory, 'precache-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  // Headers apply on Cloudflare Pages and Netlify; other hosts must use equivalent rules.
  await writeFile(path.join(directory, '_headers'), basePath + '/sw.js\n  Cache-Control: no-cache, no-store, must-revalidate\n  Service-Worker-Allowed: ' + basePath + '/\n' + basePath + '/manifest.webmanifest\n  Cache-Control: no-cache\n/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: no-referrer\n');
  await writeFile(path.join(directory, '.nojekyll'), '');
  if (!options.skipLicenseNotices) await generateLicenseNotices(directory);
  const bytes = manifest.entries.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(`PWA ${manifest.version}: ${manifest.entries.length} verified resources, ${(bytes / 1024 / 1024).toFixed(2)} MiB. Output: ${directory}`);
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await stat(path.join(root, 'out/index.html'));
  await buildPwa();
}
